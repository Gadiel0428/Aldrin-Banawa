type DotNestedKeys<T, Prefix extends string = ''> = {
  [K in keyof T & string]: T[K] extends string
    ? `${Prefix}${K}`
    : DotNestedKeys<T[K], `${Prefix}${K}.`>;
}[keyof T & string];

